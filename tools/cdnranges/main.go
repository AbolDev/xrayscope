// Command cdnranges downloads the published edge address ranges of the
// supported CDNs and writes internal/classify/cdn_ranges.txt.
//
//	go run ./tools/cdnranges
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/netip"
	"os"
	"sort"
	"strings"
	"time"
)

var client = &http.Client{Timeout: 60 * time.Second}

func get(url string) ([]byte, error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return nil, fmt.Errorf("%s: HTTP %d", url, resp.StatusCode)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 32<<20))
}

func lines(url string) ([]string, error) {
	b, err := get(url)
	if err != nil {
		return nil, err
	}
	var out []string
	sc := bufio.NewScanner(strings.NewReader(string(b)))
	for sc.Scan() {
		l := strings.TrimSpace(sc.Text())
		if l != "" && !strings.HasPrefix(l, "#") {
			out = append(out, l)
		}
	}
	return out, nil
}

func main() {
	result := map[string][]string{}
	add := func(name string, cidrs []string, err error) {
		if err != nil {
			fmt.Fprintln(os.Stderr, "warning:", name, err)
			return
		}
		result[name] = append(result[name], cidrs...)
	}

	v4, err4 := lines("https://www.cloudflare.com/ips-v4")
	v6, err6 := lines("https://www.cloudflare.com/ips-v6")
	if err4 != nil || err6 != nil {
		fmt.Fprintln(os.Stderr, "warning: cloudflare", err4, err6)
	} else {
		add("Cloudflare", append(v4, v6...), nil)
	}

	var fastly struct {
		A  []string `json:"addresses"`
		A6 []string `json:"ipv6_addresses"`
	}
	b, err := get("https://api.fastly.com/public-ip-list")
	if err == nil {
		err = json.Unmarshal(b, &fastly)
	}
	add("Fastly", append(fastly.A, fastly.A6...), err)

	var aws struct {
		P  []struct{ Prefix, Service string } `json:"prefixes"`
		P6 []struct {
			Prefix  string `json:"ipv6_prefix"`
			Service string
		} `json:"ipv6_prefixes"`
	}
	b, err = get("https://ip-ranges.amazonaws.com/ip-ranges.json")
	var cf []string
	if err == nil {
		err = json.Unmarshal(b, &aws)
	}
	for _, p := range aws.P {
		if p.Service == "CLOUDFRONT" {
			cf = append(cf, p.Prefix)
		}
	}
	for _, p := range aws.P6 {
		if p.Service == "CLOUDFRONT" {
			cf = append(cf, p.Prefix)
		}
	}
	add("Amazon CloudFront", cf, err)

	arv, err := lines("https://www.arvancloud.ir/en/ips.txt")
	add("ArvanCloud", arv, err)

	var gcore struct {
		A  []string `json:"addresses"`
		A6 []string `json:"addresses_v6"`
	}
	b, err = get("https://api.gcore.com/cdn/public-ip-list")
	if err == nil {
		err = json.Unmarshal(b, &gcore)
	}
	add("Gcore", append(gcore.A, gcore.A6...), err)

	out, err := os.Create("internal/classify/cdn_ranges.txt")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer out.Close()
	fmt.Fprintf(out, "# Edge ranges published by the CDNs themselves; generated by tools/cdnranges on %s.\n# provider|prefix\n", time.Now().UTC().Format("2006-01-02"))
	names := make([]string, 0, len(result))
	for n := range result {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		seen := map[netip.Prefix]bool{}
		count := 0
		for _, c := range result[n] {
			p, err := netip.ParsePrefix(strings.TrimSpace(c))
			if err != nil {
				if a, err2 := netip.ParseAddr(strings.TrimSpace(c)); err2 == nil {
					p = netip.PrefixFrom(a, a.BitLen())
				} else {
					continue
				}
			}
			p = p.Masked()
			if !seen[p] {
				seen[p] = true
				fmt.Fprintf(out, "%s|%s\n", n, p)
				count++
			}
		}
		fmt.Printf("%-18s %d prefixes\n", n, count)
	}
}
